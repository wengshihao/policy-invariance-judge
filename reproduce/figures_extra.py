"""Supplementary plots NOT in the published paper.

These were used during development and are kept as convenience helpers
for users inspecting their own audits. The published paper only carries
``overview.pdf`` (Fig. 1) and ``fig5_disagreement.pdf`` (Fig. 5) in the
main text plus the eight appendix figures generated by
``reproduce/figures_appendix.py``.

This script regenerates:

  figures/extra_cross_model_forest.pdf   — forest plot of certified Δ_flip
  figures/extra_transform_heatmap.pdf    — model × transform Δ_flip heatmap
  figures/extra_ambiguity_moderation.pdf — clear vs ambiguous Δ_flip
  figures/extra_judge_cards_panel.pdf    — visual Judge Card panel

Usage
-----
    python reproduce/figures_extra.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pij.config import FIGURES_DIR
from pij.figures import (
    fig_ambiguity_moderation,
    fig_cross_model_forest,
    fig_judge_cards,
    fig_transform_heatmap,
)
from pij.judge_card import build_judge_card
from pij.metrics import delta_flip
from reproduce._common import (
    PAPER_MODELS,
    load_all_judge_results,
    load_strict_lenient,
)


def main() -> None:
    print("Loading model results...")
    model_results = load_all_judge_results(PAPER_MODELS)
    if not model_results:
        print("No judge results found. Run scripts/run_judge.py first.")
        return

    per_model_delta = {label: delta_flip(model_results[label])
                       for label in model_results}

    print("extra_cross_model_forest")
    fig_cross_model_forest(per_model_delta, FIGURES_DIR / "extra_cross_model_forest.pdf")

    print("extra_transform_heatmap")
    fig_transform_heatmap(per_model_delta, FIGURES_DIR / "extra_transform_heatmap.pdf")

    print("extra_ambiguity_moderation")
    fig_ambiguity_moderation(per_model_delta, FIGURES_DIR / "extra_ambiguity_moderation.pdf")

    print("extra_judge_cards_panel")
    cards = {}
    for label, model_id in PAPER_MODELS.items():
        if label not in model_results:
            continue
        try:
            sl_rows = load_strict_lenient(model_id)
        except FileNotFoundError:
            sl_rows = None
        cards[label] = build_judge_card(model_id, model_results[label],
                                        strict_lenient_rows=sl_rows)
    if cards:
        fig_judge_cards(cards, FIGURES_DIR / "extra_judge_cards_panel.pdf")

    print(f"\nSupplementary figures written to {FIGURES_DIR}")


if __name__ == "__main__":
    main()
